"""Google Earth Engine AlphaEarth Sample Augmentation workflow (Ticket #08).

Uses Google's Annual Satellite Embedding V1 collection
(``GOOGLE/SATELLITE_EMBEDDING/V1/ANNUAL``) to discover candidate training
locations via per-class sample-prototype cosine similarity, per-class
thresholding, and vector-centroid deduplication mapped strictly to a configured
:class:`ClassSchema` (ADR-0005).
"""

from __future__ import annotations

import math
import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Literal

from lc_framework._gee import require_ee
from lc_framework.config import ClassSchema, ProjectConfig

ALPHAEARTH_COLLECTION: str = "GOOGLE/SATELLITE_EMBEDDING/V1/ANNUAL"
DEFAULT_SIMILARITY_THRESHOLD: float = 0.90
UNCALIBRATED_QA_DISCLAIMER: str = (
    "UNCALIBRATED DIAGNOSTIC QA AID ONLY — softmax similarity reflects relative "
    "embedding-space competition, NOT calibrated land-cover probabilities. "
    "Do NOT pass this overlay as a Class Probability Stack."
)

ThresholdInput = float | Mapping[int, float] | Mapping[str, float] | Mapping[int | str, float]


def _require_finite_number(value: Any, *, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise TypeError(f"{name} must be a real number (not bool), got {value!r}.")
    num = float(value)
    if not math.isfinite(num):
        raise ValueError(f"{name} must be finite, got {value!r}.")
    return num


def _require_valid_threshold(value: Any, *, label: str = "Threshold") -> float:
    num = _require_finite_number(value, name=label)
    if not (-1.0 <= num < 1.0):
        raise ValueError(f"{label} must lie in [-1.0, 1.0), got {value!r}.")
    return num


def _require_int_class_id(value: Any) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"Class ID must be an integer (not bool), got {value!r}.")
    return int(value)


def _resolve_scale_m(scale_m: float | None, config: ProjectConfig | None) -> float:
    if scale_m is not None:
        val = _require_finite_number(scale_m, name="scale_m")
        if val <= 0.0:
            raise ValueError(f"scale_m must be > 0, got {scale_m!r}.")
        return val
    if config is not None:
        return float(config.scale_m)
    return 10.0


@dataclass(frozen=True)
class SampleAugmentationParams:
    """Parameters governing AlphaEarth embedding cosine-similarity Sample Augmentation."""

    year: int = 2024
    scale_m: float = 10.0
    tile_scale: int = 4
    default_threshold: float = DEFAULT_SIMILARITY_THRESHOLD
    eight_connected: bool = False
    max_pixels: float = 1e10
    region_buffer_m: float = 5000.0
    materialize_per_class: bool = False
    wait_seconds: float = 0.0
    collection_id: str = ALPHAEARTH_COLLECTION

    def __post_init__(self) -> None:
        if isinstance(self.year, bool) or not (1900 <= self.year <= 2100):
            raise ValueError(f"year must lie in [1900, 2100], got {self.year!r}.")
        scale_val = _require_finite_number(self.scale_m, name="scale_m")
        if scale_val <= 0.0:
            raise ValueError(f"scale_m must be > 0, got {self.scale_m!r}.")
        if isinstance(self.tile_scale, bool) or self.tile_scale < 1:
            raise ValueError(f"tile_scale must be >= 1, got {self.tile_scale!r}.")
        _require_valid_threshold(self.default_threshold, label="default_threshold")
        max_px = _require_finite_number(self.max_pixels, name="max_pixels")
        if max_px <= 0.0:
            raise ValueError(f"max_pixels must be > 0, got {self.max_pixels!r}.")
        buf = _require_finite_number(self.region_buffer_m, name="region_buffer_m")
        if buf < 0.0:
            raise ValueError(f"region_buffer_m must be >= 0, got {self.region_buffer_m!r}.")
        wait = _require_finite_number(self.wait_seconds, name="wait_seconds")
        if wait < 0.0:
            raise ValueError(f"wait_seconds must be >= 0, got {self.wait_seconds!r}.")
        if not self.collection_id.strip():
            raise ValueError("collection_id cannot be empty.")


@dataclass(frozen=True)
class DiagnosticSoftmaxOverlay:
    """Uncalibrated softmax QA visualization over per-class cosine similarities."""

    image: Any
    band_names: tuple[str, ...]
    class_ids: tuple[int, ...]
    class_schema: ClassSchema
    temperature: float
    calibrated: Literal[False] = False
    disclaimer: str = UNCALIBRATED_QA_DISCLAIMER

    def __post_init__(self) -> None:
        if self.calibrated is not False:
            raise ValueError("DiagnosticSoftmaxOverlay.calibrated must always be False.")


@dataclass(frozen=True)
class SampleAugmentationResult:
    """Outputs generated by :func:`run_sample_augmentation`."""

    embedding_image: Any
    similarity_stack: Any
    candidate_points: Any
    thresholds: dict[int, float]
    class_ids: tuple[int, ...]
    class_schema: ClassSchema
    diagnostic_overlay: DiagnosticSoftmaxOverlay | None = None


def _resolve_schema(
    class_schema: ClassSchema | None,
    config: ProjectConfig | None,
    *,
    caller: str,
) -> ClassSchema:
    if class_schema is not None:
        if config is not None and config.class_schema != class_schema:
            raise ValueError(
                f"{caller}: explicit class_schema does not match config.class_schema."
            )
        return class_schema
    if config is not None:
        return config.class_schema
    raise ValueError(f"{caller}: provide either class_schema or config.")


def resolve_class_ids(
    class_schema: ClassSchema,
    class_ids: Sequence[int] | None = None,
) -> tuple[int, ...]:
    """Validate and order target class IDs strictly according to ``class_schema``."""
    if class_ids is None:
        return class_schema.class_ids
    requested = {_require_int_class_id(cid) for cid in class_ids}
    if not requested:
        raise ValueError("class_ids cannot be empty when explicitly provided.")
    unknown = requested - set(class_schema.class_ids)
    if unknown:
        raise ValueError(
            f"Requested class_ids {sorted(unknown)} are not defined in ClassSchema "
            f"{class_schema.class_ids}."
        )
    return tuple(cid for cid in class_schema.class_ids if cid in requested)


def resolve_class_thresholds(
    class_schema: ClassSchema,
    *,
    class_ids: Sequence[int] | None = None,
    thresholds: ThresholdInput | None = None,
    default_threshold: float = DEFAULT_SIMILARITY_THRESHOLD,
) -> dict[int, float]:
    """Resolve and validate per-class cosine-similarity thresholds ordered by ``ClassSchema``.

    ``thresholds`` may be a uniform float applied to all selected classes, or a
    mapping keyed by integer class ID or canonical class name.
    """
    default_val = _require_valid_threshold(default_threshold, label="default_threshold")
    ordered_ids = resolve_class_ids(class_schema, class_ids)

    if thresholds is None:
        return {cid: default_val for cid in ordered_ids}

    if isinstance(thresholds, bool):
        raise TypeError("thresholds cannot be a bool; expected float or Mapping.")

    if isinstance(thresholds, int | float):
        t_val = _require_valid_threshold(thresholds, label="Threshold")
        return {cid: t_val for cid in ordered_ids}

    if isinstance(thresholds, Mapping):
        resolved_map: dict[int, float] = {}
        for raw_key, raw_val in thresholds.items():
            if isinstance(raw_key, str):
                cid = class_schema.id_for(raw_key)
            else:
                cid = _require_int_class_id(raw_key)
                if cid not in class_schema.class_ids:
                    raise KeyError(f"Class ID {cid} not found in ClassSchema.")
            resolved_map[cid] = _require_valid_threshold(
                raw_val, label=f"Threshold for class {cid}"
            )
        return {cid: resolved_map.get(cid, default_val) for cid in ordered_ids}

    raise TypeError(
        "thresholds must be None, a scalar float in [-1.0, 1.0), or a mapping of "
        "{class_id_or_name: threshold}."
    )


def get_alphaearth_mosaic(
    year: int,
    region: Any,
    *,
    collection_id: str = ALPHAEARTH_COLLECTION,
) -> Any:
    """Build the annual AlphaEarth Satellite Embedding mosaic clipped to ``region``."""
    if isinstance(year, bool) or not (1900 <= year <= 2100):
        raise ValueError(f"year must lie in [1900, 2100], got {year!r}.")
    if not collection_id.strip():
        raise ValueError("collection_id cannot be empty.")
    ee = require_ee("AlphaEarth embedding mosaic retrieval")
    start = ee.Date.fromYMD(int(year), 1, 1)
    end = start.advance(1, "year")
    return (
        ee.ImageCollection(collection_id)
        .filterDate(start, end)
        .filterBounds(region)
        .mosaic()
        .clip(region)
    )


def compute_class_cosine_similarity(
    embedding_image: Any,
    training_fc: Any,
    *,
    class_id: int,
    class_property: str = "class_id",
    scale_m: float = 10.0,
    tile_scale: int = 4,
) -> Any:
    """Compute per-sample prototype cosine similarity averaged across a single class.

    AlphaEarth embedding vectors are unit-norm, so dot products directly yield
    pixel-level cosine similarity in ``[-1, 1]`` while preserving multi-modal
    within-class variation across sample prototypes. Returns a single band
    named ``sim_<class_id>``. When ``training_fc`` contains zero valid points
    for ``class_id``, returns a masked ``0`` band with name ``sim_<class_id>``
    instead of failing on an empty ImageCollection rename.
    """
    cid = _require_int_class_id(class_id)
    if not class_property.strip():
        raise ValueError("class_property cannot be empty.")
    scale_val = _require_finite_number(scale_m, name="scale_m")
    if scale_val <= 0.0:
        raise ValueError(f"scale_m must be > 0, got {scale_m!r}.")
    if isinstance(tile_scale, bool) or tile_scale < 1:
        raise ValueError(f"tile_scale must be >= 1, got {tile_scale!r}.")

    ee = require_ee("AlphaEarth per-class cosine similarity")
    class_pts = training_fc.filter(ee.Filter.eq(class_property, cid))
    sampled = embedding_image.sampleRegions(
        collection=class_pts,
        properties=[],
        scale=scale_val,
        tileScale=int(tile_scale),
    )
    band_names = embedding_image.bandNames()
    sim_band_name = f"sim_{cid}"

    def _point_similarity(feat: Any) -> Any:
        f = ee.Feature(feat)
        vec_img = ee.Image(f.toArray(band_names)).arrayFlatten([band_names])
        return vec_img.multiply(embedding_image).reduce(ee.Reducer.sum()).rename("similarity")

    sim_list = sampled.toList(sampled.size()).map(_point_similarity)
    mean_sim = ee.ImageCollection(sim_list).mean().rename(sim_band_name)
    empty_band = (
        ee.Image.constant(0)
        .float()
        .updateMask(ee.Image.constant(0))
        .rename(sim_band_name)
    )
    return ee.Image(ee.Algorithms.If(sampled.size().gt(0), mean_sim, empty_band))


def build_class_similarity_stack(
    embedding_image: Any,
    training_fc: Any,
    *,
    class_schema: ClassSchema | None = None,
    config: ProjectConfig | None = None,
    class_ids: Sequence[int] | None = None,
    class_property: str = "class_id",
    scale_m: float | None = None,
    tile_scale: int = 4,
    materialize_per_class: bool = False,
    wait_seconds: float = 0.0,
) -> Any:
    """Build multi-band ``sim_<id>`` cosine-similarity stack ordered by ``ClassSchema``."""
    schema = _resolve_schema(class_schema, config, caller="build_class_similarity_stack")
    ordered_ids = resolve_class_ids(schema, class_ids)
    resolved_scale = _resolve_scale_m(scale_m, config)
    wait = _require_finite_number(wait_seconds, name="wait_seconds")
    if wait < 0.0:
        raise ValueError(f"wait_seconds must be >= 0, got {wait_seconds!r}.")

    ee = require_ee("AlphaEarth similarity stack construction")
    sample_region = training_fc.geometry().bounds() if materialize_per_class else None
    sim_bands: list[Any] = []
    for idx, cid in enumerate(ordered_ids, start=1):
        band = compute_class_cosine_similarity(
            embedding_image,
            training_fc,
            class_id=cid,
            class_property=class_property,
            scale_m=resolved_scale,
            tile_scale=tile_scale,
        )
        if materialize_per_class and sample_region is not None:
            band.reduceRegion(
                reducer=ee.Reducer.first(),
                geometry=sample_region,
                scale=max(resolved_scale, 30.0),
                maxPixels=1e8,
                bestEffort=True,
            ).getInfo()
            if wait > 0.0 and idx < len(ordered_ids):
                time.sleep(wait)
        sim_bands.append(band)

    return ee.Image.cat(sim_bands)


def extract_class_candidate_centroids(
    sim_stack: Any,
    *,
    class_id: int,
    class_schema: ClassSchema,
    region: Any,
    threshold: float = DEFAULT_SIMILARITY_THRESHOLD,
    scale_m: float = 10.0,
    eight_connected: bool = False,
    max_pixels: float = 1e10,
    class_property: str = "class_id",
) -> Any:
    """Threshold ``sim_<id>``, vectorize connected matches, and deduplicate to centroids."""
    cid = _require_int_class_id(class_id)
    t_val = _require_valid_threshold(threshold, label="threshold")
    scale_val = _require_finite_number(scale_m, name="scale_m")
    if scale_val <= 0.0:
        raise ValueError(f"scale_m must be > 0, got {scale_m!r}.")
    max_px = _require_finite_number(max_pixels, name="max_pixels")
    if max_px <= 0.0:
        raise ValueError(f"max_pixels must be > 0, got {max_pixels!r}.")
    if not class_property.strip():
        raise ValueError("class_property cannot be empty.")

    class_name = class_schema.name_for(cid)

    ee = require_ee("AlphaEarth candidate centroid extraction")
    band_name = f"sim_{cid}"
    sim_band = sim_stack.select(band_name)
    polygons = (
        sim_band.gt(t_val)
        .selfMask()
        .reduceToVectors(
            scale=scale_val,
            eightConnected=bool(eight_connected),
            maxPixels=max_px,
            geometry=region,
        )
    )

    def _to_centroid_feature(feat: Any) -> Any:
        poly = ee.Feature(feat)
        poly_geom = poly.geometry()
        # Sample patch similarity over poly_geom (guaranteed inside the matched patch,
        # unlike concave polygon centroids) and emit a clean Feature without label/count.
        conf = sim_band.reduceRegion(
            reducer=ee.Reducer.mean(),
            geometry=poly_geom,
            scale=scale_val,
            maxPixels=max_px,
        ).get(band_name)
        return ee.Feature(
            poly_geom.centroid(maxError=1),
            {
                class_property: cid,
                "class_name": class_name,
                "confidence": conf,
                "sample_source": "alphaearth_similarity",
            },
        )

    return polygons.map(_to_centroid_feature)


def extract_all_candidate_centroids(
    sim_stack: Any,
    *,
    class_schema: ClassSchema | None = None,
    config: ProjectConfig | None = None,
    region: Any,
    class_ids: Sequence[int] | None = None,
    thresholds: ThresholdInput | None = None,
    default_threshold: float = DEFAULT_SIMILARITY_THRESHOLD,
    scale_m: float | None = None,
    eight_connected: bool = False,
    max_pixels: float = 1e10,
    class_property: str = "class_id",
) -> Any:
    """Extract and flatten deduplicated candidate points across selected ``ClassSchema`` classes."""
    schema = _resolve_schema(class_schema, config, caller="extract_all_candidate_centroids")
    resolved_scale = _resolve_scale_m(scale_m, config)
    threshold_map = resolve_class_thresholds(
        schema,
        class_ids=class_ids,
        thresholds=thresholds,
        default_threshold=default_threshold,
    )
    ee = require_ee("AlphaEarth multi-class candidate extraction")

    collections = [
        extract_class_candidate_centroids(
            sim_stack,
            class_id=cid,
            class_schema=schema,
            region=region,
            threshold=t_val,
            scale_m=resolved_scale,
            eight_connected=eight_connected,
            max_pixels=max_pixels,
            class_property=class_property,
        )
        for cid, t_val in threshold_map.items()
    ]
    return ee.FeatureCollection(collections).flatten()


def build_diagnostic_similarity_overlay(
    sim_stack: Any,
    *,
    class_schema: ClassSchema | None = None,
    config: ProjectConfig | None = None,
    class_ids: Sequence[int] | None = None,
    temperature: float = 10.0,
) -> DiagnosticSoftmaxOverlay:
    """Build an explicitly uncalibrated softmax QA overlay from similarity bands.

    Uses ``qa_softmax_<id>`` band names and ``is_calibrated_probability=False``
    metadata so this diagnostic visual aid is never confused with a calibrated
    ``Class Probability Stack``.
    """
    temp_val = _require_finite_number(temperature, name="temperature")
    if temp_val <= 0.0:
        raise ValueError(f"temperature must be > 0, got {temperature!r}.")
    schema = _resolve_schema(
        class_schema, config, caller="build_diagnostic_similarity_overlay"
    )
    ordered_ids = resolve_class_ids(schema, class_ids)
    ee = require_ee("AlphaEarth diagnostic softmax QA overlay")

    sim_bands = [f"sim_{cid}" for cid in ordered_ids]
    qa_bands = tuple(f"qa_softmax_{cid}" for cid in ordered_ids)

    selected = sim_stack.select(sim_bands)
    max_sim = selected.reduce(ee.Reducer.max())
    scaled = selected.subtract(max_sim).multiply(temp_val)
    exp_img = scaled.exp()
    denom = exp_img.reduce(ee.Reducer.sum())
    overlay_img = (
        exp_img.divide(denom)
        .rename(list(qa_bands))
        .set(
            {
                "is_calibrated_probability": False,
                "overlay_role": "diagnostic_qa_only",
                "temperature": temp_val,
                "disclaimer": UNCALIBRATED_QA_DISCLAIMER,
            }
        )
    )

    return DiagnosticSoftmaxOverlay(
        image=overlay_img,
        band_names=qa_bands,
        class_ids=ordered_ids,
        class_schema=schema,
        temperature=temp_val,
        calibrated=False,
        disclaimer=UNCALIBRATED_QA_DISCLAIMER,
    )


def merge_augmented_samples(
    original_fc: Any,
    augmented_fc: Any,
    *,
    source_property: str = "sample_source",
    original_label: str = "reference",
    augmented_label: str = "alphaearth_similarity",
) -> Any:
    """Tag original and augmented points with provenance metadata and merge."""
    if not source_property.strip():
        raise ValueError("source_property cannot be empty.")
    ee = require_ee("AlphaEarth sample merge")
    tagged_orig = original_fc.map(
        lambda feat: ee.Feature(feat).set(source_property, original_label)
    )
    tagged_aug = augmented_fc.map(
        lambda feat: ee.Feature(feat).set(source_property, augmented_label)
    )
    return tagged_orig.merge(tagged_aug)


def export_augmented_samples_to_asset(
    candidates: Any,
    *,
    asset_id: str,
    description: str = "AlphaEarth_Augmented_Samples",
    dry_run: bool = False,
) -> Any | None:
    """Export augmented candidate FeatureCollection to a Google Earth Engine asset."""
    if not asset_id.strip():
        raise ValueError("asset_id cannot be empty.")
    if not description.strip():
        raise ValueError("description cannot be empty.")
    if dry_run:
        return None
    ee = require_ee("AlphaEarth asset export")
    task = ee.batch.Export.table.toAsset(
        collection=candidates,
        description=description,
        assetId=asset_id,
    )
    task.start()
    return task


def export_augmented_samples_to_drive(
    candidates: Any,
    *,
    description: str = "AlphaEarth_Augmented_Samples",
    folder: str = "LC_Framework",
    file_name_prefix: str | None = None,
    file_format: str = "CSV",
    dry_run: bool = False,
) -> Any | None:
    """Export augmented candidate FeatureCollection to Google Drive."""
    if not description.strip():
        raise ValueError("description cannot be empty.")
    if not folder.strip():
        raise ValueError("folder cannot be empty.")
    if dry_run:
        return None
    ee = require_ee("AlphaEarth Drive export")
    task = ee.batch.Export.table.toDrive(
        collection=candidates,
        description=description,
        folder=folder,
        fileNamePrefix=file_name_prefix or description,
        fileFormat=file_format,
    )
    task.start()
    return task


def run_sample_augmentation(
    training_fc: Any,
    *,
    class_schema: ClassSchema | None = None,
    config: ProjectConfig | None = None,
    region: Any | None = None,
    class_ids: Sequence[int] | None = None,
    thresholds: ThresholdInput | None = None,
    params: SampleAugmentationParams | None = None,
    class_property: str = "class_id",
    include_diagnostic_overlay: bool = False,
    temperature: float = 10.0,
) -> SampleAugmentationResult:
    """Run the end-to-end AlphaEarth Sample Augmentation pipeline in Earth Engine."""
    schema = _resolve_schema(class_schema, config, caller="run_sample_augmentation")
    cfg_params = (
        params
        if params is not None
        else SampleAugmentationParams(
            scale_m=float(config.scale_m) if config is not None else 10.0
        )
    )
    require_ee("AlphaEarth Sample Augmentation")

    resolved_thresholds = resolve_class_thresholds(
        schema,
        class_ids=class_ids,
        thresholds=thresholds,
        default_threshold=cfg_params.default_threshold,
    )
    ordered_ids = tuple(resolved_thresholds.keys())

    target_region = (
        region
        if region is not None
        else training_fc.geometry().bounds().buffer(cfg_params.region_buffer_m)
    )
    embedding_img = get_alphaearth_mosaic(
        cfg_params.year,
        target_region,
        collection_id=cfg_params.collection_id,
    )
    sim_stack = build_class_similarity_stack(
        embedding_img,
        training_fc,
        class_schema=schema,
        class_ids=ordered_ids,
        class_property=class_property,
        scale_m=cfg_params.scale_m,
        tile_scale=cfg_params.tile_scale,
        materialize_per_class=cfg_params.materialize_per_class,
        wait_seconds=cfg_params.wait_seconds,
    )
    candidate_points = extract_all_candidate_centroids(
        sim_stack,
        class_schema=schema,
        region=target_region,
        class_ids=ordered_ids,
        thresholds=resolved_thresholds,
        scale_m=cfg_params.scale_m,
        eight_connected=cfg_params.eight_connected,
        max_pixels=cfg_params.max_pixels,
        class_property=class_property,
    )
    overlay = (
        build_diagnostic_similarity_overlay(
            sim_stack,
            class_schema=schema,
            class_ids=ordered_ids,
            temperature=temperature,
        )
        if include_diagnostic_overlay
        else None
    )

    return SampleAugmentationResult(
        embedding_image=embedding_img,
        similarity_stack=sim_stack,
        candidate_points=candidate_points,
        thresholds=resolved_thresholds,
        class_ids=ordered_ids,
        class_schema=schema,
        diagnostic_overlay=overlay,
    )
